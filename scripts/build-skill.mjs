import { mkdir, cp, rm } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build as webBuild } from 'vite'
import { build } from 'esbuild'

export async function buildSkill(root) {
  const skill = resolve(root, '.agents/skills/mindweave')
  await webBuild({ root, logLevel: 'silent' })
  await mkdir(resolve(skill, 'scripts/runtime'), { recursive: true })
  await build({ entryPoints: [resolve(root, 'src/integration/cli.ts')], outfile: resolve(skill, 'scripts/runtime/cli.mjs'),
    bundle: true, platform: 'node', format: 'esm', target: 'node22',
    define: { __MINDWEAVE_PACKAGE__: 'true', __MINDWEAVE_SKILL__: 'true' }, logLevel: 'warning',
    banner: { js: '// Generated by npm run build:skill. Edit src/, then rebuild the portable skill.' } })
  await rm(resolve(skill, 'assets/web'), { recursive: true, force: true })
  await cp(resolve(root, 'dist'), resolve(skill, 'assets/web'), { recursive: true })
  await mkdir(resolve(skill, 'assets/licenses'), { recursive: true })
  await cp(resolve(root, 'LICENSE'), resolve(skill, 'assets/licenses/mindweave.txt'))
  for (const name of ['react', 'react-dom', 'scheduler']) {
    await cp(resolve(root, 'node_modules', name, 'LICENSE'), resolve(skill, `assets/licenses/${name}.txt`))
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildSkill(resolve(dirname(fileURLToPath(import.meta.url)), '..'))
}
